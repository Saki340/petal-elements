/**
 * @fileoverview Generates tokens/versions/v34/values/: one Sass `$values` map
 * per v34 token set that the Expressive features use (button sizes, toggle
 * button colors, filled FAB colors, ...), plus the springs.
 *
 *     @use '../../tokens/versions/v34/values/md-comp-button-small' as small;
 *     height: map.get(small.$values, 'container-height');  // 40px
 *
 * Keys are the token names without the set prefix, dots as dashes
 * (`md.comp.button.small.container.shape.round` -> `container-shape-round`).
 * References to system and reference tokens (except palette tones) become
 * `var(--md-sys-..., value)` like in the stable components, so runtime theming
 * still works. A typescale reference such as `label-text` expands to
 * `label-text-font`, `-size`, `-line-height`, `-weight` and `-tracking`.
 */

import type {ComposeFile} from './compose.js';
import {isToken, SOURCES, Token, walk} from './dtcg.js';
import type {WebFile} from './web.js';

/** v34 token sets to generate, by Sass module name. */
export const VALUE_MODULES = [
  'md-comp-button',
  'md-comp-button-xsmall',
  'md-comp-button-small',
  'md-comp-button-medium',
  'md-comp-button-large',
  'md-comp-button-xlarge',
  'md-comp-button-filled',
  'md-comp-button-tonal',
  'md-comp-button-outlined',
  'md-comp-button-elevated',
  ...['xsmall', 'small', 'medium', 'large', 'xlarge'].flatMap((size) => [
    `md-comp-button-group-standard-${size}`,
    `md-comp-button-group-connected-${size}`,
  ]),
  ...['primary', 'secondary', 'tertiary'].flatMap((color) => [
    `md-comp-fab-${color}`,
    `md-comp-extended-fab-${color}`,
  ]),
];

/**
 * Compose token objects to generate (tokens/versions/compose/values/), by
 * Kotlin object name without `Tokens`. Used by components whose values follow
 * Jetpack Compose.
 */
export const COMPOSE_VALUE_MODULES = [
  'AppBar',
  'AppBarSmall',
  'AppBarMediumFlexible',
  'AppBarLargeFlexible',
  'ElevatedCard',
  'FilledCard',
  'OutlinedCard',
  'List',
  'LoadingIndicator',
  'PlainTooltip',
  'SegmentedMenu',
  'Snackbar',
  'StandardMenu',
];

/** Longest dotted prefix shared by all names, e.g. `md.comp.button.small`. */
function commonPrefix(names: string[]) {
  let parts = names[0].split('.');
  for (const name of names) {
    const other = name.split('.');
    let i = 0;
    while (i < parts.length && i < other.length - 1 && parts[i] === other[i]) i++;
    parts = parts.slice(0, i);
  }
  return parts.join('.');
}

function composeHeader(title: string) {
  const compose = SOURCES.compose;
  return [
    '//',
    `// ${compose.copyright}`,
    '// SPDX-License-Identifier: Apache-2.0',
    '//',
    '// Generated by petal-elements ("npm run tokens"). Do not edit.',
    `// ${title}`,
    `// Jetpack Compose Material 3 tokens`,
    `// (${compose.repository}/tree/${compose.commit}/${compose.path}).`,
    '//',
    '',
  ].join('\n');
}

function header(title: string) {
  const web = SOURCES.web;
  return [
    '//',
    `// ${web.copyright}`,
    '// SPDX-License-Identifier: Apache-2.0',
    '//',
    '// Generated by petal-elements ("npm run tokens"). Do not edit.',
    `// ${title}`,
    `// Material Design web tokens version ${web.version}`,
    `// (${web.repository}/tree/${web.commit}/${web.path}).`,
    '//',
    '',
  ].join('\n');
}

function literal(token: Token): string {
  const v = token.$value as never;
  switch (token.$type) {
    case 'color':
      return (v as {hex: string}).hex;
    case 'dimension':
    case 'duration': {
      const d = v as {value: number; unit: string};
      return `${d.value}${d.unit}`;
    }
    case 'cubicBezier':
      return `cubic-bezier(${(v as number[]).join(', ')})`;
    case 'fontFamily':
      return [v].flat().map((f: string) => (/\s/.test(f) ? `'${f}'` : f)).join(', ');
    case 'number':
    case 'fontWeight':
      return String(v);
    default:
      if (typeof v === 'string') return v;
      throw new Error(`No CSS literal for ${JSON.stringify(v)}`);
  }
}

// Palette tones are not in sys.css (like in the stable components, a system
// color falls back to the tone's value, not to a palette property).
const isSystem = (path: string) =>
  /^md\.(sys|ref)\./.test(path) && !path.startsWith('md.ref.palette.');
const cssName = (path: string) => `--${path.replace(/\./g, '-')}`;

export function buildValueModules(files: WebFile[], sysCss: string): Map<string, string> {
  // All default-context tokens by name.
  const tokens = new Map<string, Token>();
  for (const file of files) {
    if (!file.context) for (const [path, token] of walk(file.tokens)) tokens.set(path, token);
  }

  /** CSS value of a token, with `var()` for system tokens it refers to. */
  const value = (path: string, depth = 0): string => {
    if (depth > 20) throw new Error(`Reference loop at ${path}`);
    const token = tokens.get(path);
    if (!token || !isToken(token)) throw new Error(`Unknown token ${path}`);
    const v = token.$value;
    if (typeof v === 'string' && /^\{.*\}$/.test(v)) {
      const target = v.slice(1, -1);
      const resolved = value(target, depth + 1);
      return isSystem(target) ? `var(${cssName(target)}, ${resolved})` : resolved;
    }
    if (token.$type === 'typography') {
      throw new Error(`${path}: expand typography before calling value()`);
    }
    return literal(token);
  };

  const output = new Map<string, string>();
  for (const module of VALUE_MODULES) {
    const file = files.find((f) => f.module === module && !f.context);
    if (!file) throw new Error(`No v34 token file ${module}`);
    const entries: Array<[string, string]> = [];
    // md.comp.button.small.container.height -> container-height
    const prefix = commonPrefix([...walk(file.tokens)].map(([path]) => path));
    for (const [path, token] of walk(file.tokens)) {
      const key = path.slice(prefix.length + 1).replace(/\./g, '-');
      const v = token.$value;
      const target = typeof v === 'string' && /^\{.*\}$/.test(v) ? v.slice(1, -1) : '';
      if (token.$type === 'typography' || tokens.get(target)?.$type === 'typography') {
        // A composite such as `label-text.type` whose parts are tokens of their
        // own (`label-text.font`, ...): the parts are enough.
        const base = path.replace(/\.type$/, '');
        if (!target && base !== path && tokens.has(`${base}.font`)) continue;
        // A typescale: expand into its parts, as var() of the system tokens.
        if (!target.startsWith('md.sys.typescale.')) {
          throw new Error(`${path}: typography that is not a typescale reference`);
        }
        for (const part of ['font', 'size', 'line-height', 'weight', 'tracking']) {
          entries.push([`${key}-${part}`, `var(${cssName(`${target}.${part}`)}, ${value(`${target}.${part}`)})`]);
        }
        continue;
      }
      entries.push([key, value(path)]);
    }
    entries.sort(([a], [b]) => (a < b ? -1 : 1));
    output.set(
      `_${module}.scss`,
      header(`Values of ${prefix}.*, see scripts/tokens/values.ts.`) +
        '$values: (\n' +
        entries.map(([k, v]) => `  '${k}': ${v},`).join('\n') +
        '\n);\n',
    );
  }

  // Springs, from the generated sys.css (the linear() easings are derived there).
  const springs: Array<[string, string]> = [];
  for (const m of sysCss.matchAll(/^\s*--md-sys-motion-((?:expressive-)?spring-(?:fast|default|slow)-(?:spatial|effects)(?:-duration)?): ([^;]+);$/gm)) {
    springs.push([m[1], `var(--md-sys-motion-${m[1]}, ${m[2]})`]);
  }
  if (springs.length !== 24) throw new Error(`Expected 24 spring properties, found ${springs.length}`);
  output.set(
    '_md-sys-motion-springs.scss',
    header('Spring easings (linear()) and durations, see tokens/css/sys.css.') +
      '$values: (\n' +
      springs.map(([k, v]) => `  '${k}': ${v},`).join('\n') +
      '\n);\n',
  );
  return output;
}

const kebabObject = (name: string) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

/**
 * Value maps from the Compose token objects in COMPOSE_VALUE_MODULES, like
 * buildValueModules() does for the web tokens. Differences: elevation
 * references become the level number (for `--md-elevation-level`), and a
 * typescale reference `label-text-font` expands to `label-text-font`,
 * `label-text-size`, ... Colors fall back to the light scheme.
 */
export function buildComposeValueModules(files: ComposeFile[]): Map<string, string> {
  const tokens = new Map<string, Token>();
  for (const file of files) {
    if (file.object === 'ColorDarkTokens') continue;
    for (const [path, token] of walk(file.tokens)) tokens.set(path, token);
  }

  const value = (path: string, depth = 0): string => {
    if (depth > 20) throw new Error(`Reference loop at ${path}`);
    const token = tokens.get(path);
    if (!token || !isToken(token)) throw new Error(`Unknown token ${path}`);
    const v = token.$value;
    if (typeof v === 'string' && /^\{.*\}$/.test(v)) {
      const target = v.slice(1, -1);
      const level = target.match(/^md\.sys\.elevation\.level(\d)$/);
      if (level) return level[1];
      const resolved = value(target, depth + 1);
      return isSystem(target) ? `var(${cssName(target)}, ${resolved})` : resolved;
    }
    return literal(token);
  };

  const output = new Map<string, string>();
  for (const name of COMPOSE_VALUE_MODULES) {
    const file = files.find((f) => f.object === `${name}Tokens`);
    if (!file) throw new Error(`No Compose token object ${name}Tokens`);
    const entries: Array<[string, string]> = [];
    const paths = [...walk(file.tokens)].map(([path]) => path);
    const prefix = commonPrefix(paths);
    for (const [path, token] of walk(file.tokens)) {
      const key = path.slice(prefix.length + 1).replace(/\./g, '-');
      const v = token.$value;
      const target = typeof v === 'string' && /^\{.*\}$/.test(v) ? v.slice(1, -1) : '';
      if (target.startsWith('md.sys.typescale.')) {
        const base = key.replace(/-(font|type)$/, '');
        for (const part of ['font', 'size', 'line-height', 'weight', 'tracking']) {
          entries.push([`${base}-${part}`, `var(${cssName(`${target}.${part}`)}, ${value(`${target}.${part}`)})`]);
        }
        continue;
      }
      entries.push([key, value(path)]);
    }
    entries.sort(([a], [b]) => (a < b ? -1 : 1));
    output.set(
      `_md-comp-${kebabObject(name)}.scss`,
      composeHeader(`Values of ${name}Tokens (${prefix}.*), see scripts/tokens/values.ts.`) +
        '$values: (\n' +
        entries.map(([k, v]) => `  '${k}': ${v},`).join('\n') +
        '\n);\n',
    );
  }
  return output;
}
