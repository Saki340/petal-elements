/**
 * @fileoverview Shared helpers for writing W3C Design Tokens (DTCG 2025.10)
 * files: value constructors, a token tree, and deterministic JSON output.
 */

import * as fs from 'fs';
import * as path from 'path';

export interface Source {
  description: string;
  repository: string;
  commit: string;
  path: string;
  version?: string;
  copyright: string;
  license: string;
}

export const SOURCES: {web: Source; compose: Source} = JSON.parse(
  fs.readFileSync('tokens/sources.json', 'utf8'),
);

/** Namespace for our `$extensions` data. */
export const EXT = 'dev.petal-elements';

export interface Token {
  $type?: string;
  $value: unknown;
  $deprecated?: boolean | string;
  $extensions?: Record<string, unknown>;
}

export type Group = {[key: string]: Group | Token | unknown};

export function color(hex: string): Token {
  let digits = hex.replace('#', '').toLowerCase();
  if (digits.length === 3) digits = [...digits].map((c) => c + c).join('');
  if (!/^[0-9a-f]{6}$/.test(digits)) throw new Error(`Bad color: ${hex}`);
  const components = [0, 2, 4].map((i) =>
    round(parseInt(digits.slice(i, i + 2), 16) / 255, 4),
  );
  return {
    $type: 'color',
    $value: {colorSpace: 'srgb', components, alpha: 1, hex: `#${digits}`},
  };
}

export function dimension(value: number, unit: 'px' | 'rem'): Token {
  return {$type: 'dimension', $value: {value, unit}};
}

export function duration(value: number, unit: 'ms' | 's'): Token {
  return {$type: 'duration', $value: {value, unit}};
}

export function number(value: number): Token {
  return {$type: 'number', $value: value};
}

export function alias(tokenPath: string, type?: string): Token {
  return type ? {$type: type, $value: `{${tokenPath}}`} : {$value: `{${tokenPath}}`};
}

export function round(value: number, digits: number) {
  const factor = 10 ** digits;
  return Math.round(value * factor) / factor;
}

/**
 * `BodyLargeSize` -> `body-large-size`, `Primary40` -> `primary40`,
 * `XSmall` -> `xsmall` (the web tokens spell sizes that way).
 */
export function kebab(name: string) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .toLowerCase()
    .replace(/(^|-)x-(small|large)/g, '$1x$2');
}

/**
 * Puts `token` at a dotted path. When a name is both a token and a group
 * (`a.color` and `a.color.ignore`), the token becomes the group's `$root`
 * token, as in DTCG 2025.10. Any other collision is an error.
 */
export function setToken(root: Group, tokenPath: string, token: Token) {
  const parts = tokenPath.split('.');
  let group = root;
  for (const part of parts.slice(0, -1)) {
    const next = group[part];
    if (next === undefined) {
      group[part] = {};
    } else if (isToken(next)) {
      group[part] = {$root: next};
    }
    group = group[part] as Group;
  }
  const last = parts[parts.length - 1];
  const existing = group[last];
  if (existing === undefined) {
    group[last] = token;
  } else if (!isToken(existing) && (existing as Group)['$root'] === undefined) {
    (existing as Group)['$root'] = token;
  } else {
    throw new Error(`${tokenPath}: defined twice`);
  }
}

export function isToken(value: unknown): value is Token {
  return typeof value === 'object' && value !== null && '$value' in value;
}

/** Visits every token with its dotted path (a `$root` token gets its group's path). */
export function* walk(group: Group, prefix = ''): Generator<[string, Token]> {
  if (isToken(group['$root'])) yield [prefix, group['$root']];
  for (const [key, value] of Object.entries(group)) {
    if (key.startsWith('$')) continue;
    const tokenPath = prefix ? `${prefix}.${key}` : key;
    if (isToken(value)) yield [tokenPath, value];
    else yield* walk(value as Group, tokenPath);
  }
}

/** JSON with `$` keys first and other keys sorted, so output is stable. */
export function stableJson(value: unknown): string {
  return JSON.stringify(sortKeys(value), null, 2) + '\n';
}

function sortKeys(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (typeof value !== 'object' || value === null) return value;
  const entries = Object.entries(value);
  const meta = entries.filter(([key]) => key.startsWith('$'));
  const rest = entries
    .filter(([key]) => !key.startsWith('$'))
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  return Object.fromEntries(
    [...meta, ...rest].map(([key, child]) => [key, sortKeys(child)]),
  );
}

/** Root `$description` and `$extensions` recording where a file came from. */
export function header(source: Source, file: string, extra = {}) {
  return {
    $description:
      `Generated by petal-elements from ${source.repository} at commit ` +
      `${source.commit}, file ${source.path}/${file}. ` +
      `${source.copyright}. Licensed under the ${source.license} license. ` +
      `Do not edit; run "npm run tokens" instead.`,
    $extensions: {
      [EXT]: {
        generated: true,
        repository: source.repository,
        commit: source.commit,
        file: `${source.path}/${file}`,
        ...(source.version ? {version: source.version} : {}),
        copyright: source.copyright,
        license: source.license,
        ...extra,
      },
    },
  };
}

/**
 * Collects output files in memory. `commit()` writes them, or in check mode
 * reports files that would change (including stale files to delete).
 */
export class Output {
  private files = new Map<string, string>();

  /**
   * @param dir output directory
   * @param suffix files this output owns; other files in `dir` (such as
   *     build output next to tokens/css/*.css) are left alone
   * @param ignore owned-looking files to leave alone (e.g. build output)
   */
  constructor(
    readonly dir: string,
    readonly suffix: string,
    readonly ignore?: RegExp,
  ) {}

  add(name: string, content: string) {
    if (!name.endsWith(this.suffix)) throw new Error(`${name}: expected ${this.suffix}`);
    if (this.files.has(name)) throw new Error(`${name} written twice`);
    this.files.set(name, content);
  }

  /** Returns the list of out-of-date files (empty when up to date). */
  commit(check: boolean): string[] {
    const stale: string[] = [];
    const existing = (fs.existsSync(this.dir) ? fs.readdirSync(this.dir) : []).filter(
      (name) => name.endsWith(this.suffix) && !this.ignore?.test(name),
    );
    for (const name of existing) {
      if (!this.files.has(name)) {
        stale.push(path.posix.join(this.dir, name));
        if (!check) fs.rmSync(path.join(this.dir, name));
      }
    }
    for (const [name, content] of this.files) {
      const file = path.join(this.dir, name);
      const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
      if (old === content) continue;
      stale.push(path.posix.join(this.dir, name));
      if (!check) {
        fs.mkdirSync(this.dir, {recursive: true});
        fs.writeFileSync(file, content);
      }
    }
    return stale;
  }
}
