/**
 * Writes .cache/visual/theme-v0_192.css: the v0.192 light and dark color
 * schemes as `light-dark()` custom properties. The light values equal the
 * fallbacks compiled into the components, so the baseline shows them as they
 * are built today. Runs from the repository root (`npm run test:visual`).
 */

import * as fs from 'fs';
// Compiled by `npm run build:scripts`.
import {readLegacyTokens} from '../../scripts/tokens/legacy.js';

export default function globalSetup() {
  const color = readLegacyTokens().get('md-sys-color');
  const light = color?.get('light');
  const dark = color?.get('dark');
  if (!light || !dark) throw new Error('v0.192 md-sys-color not found');
  const lines = [...light]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([name, value]) => {
      const darkValue = dark.get(name);
      const css = darkValue && darkValue !== value ? `light-dark(${value}, ${darkValue})` : value;
      return `  --md-sys-color-${name}: ${css};`;
    });
  fs.mkdirSync('.cache/visual', {recursive: true});
  fs.writeFileSync(
    '.cache/visual/theme-v0_192.css',
    '/* Generated by tests/visual/global-setup.ts from tokens/versions/v0_192. */\n' +
      `:root {\n${lines.join('\n')}\n}\n`,
  );
}
